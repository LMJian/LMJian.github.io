"""Offline teaching demo; custom event format, no model or tokenizer involved."""


def rebuild_context(events, summary, keep_users=2):
    if keep_users < 1:
        raise ValueError('keep_users must be positive')
    recent_users = [e for e in events if e['kind'] == 'user'][-keep_users:]
    return [{'kind': 'summary', 'text': summary}, *recent_users]


history = [
    {'kind': 'user', 'text': '排查重复提交订单的问题。'},
    {'kind': 'tool_call', 'text': '读取 OrderService.java'},
    {'kind': 'tool_result', 'text': '读取到 300 行代码……'},
    {'kind': 'tool_call', 'text': '运行重复请求测试'},
    {'kind': 'tool_result', 'text': '测试失败：生成两个不同订单号。'},
    {'kind': 'assistant', 'text': '检查 request_id 与唯一约束。'},
    {'kind': 'user', 'text': '不能修改现有接口字段。'},
    {'kind': 'assistant', 'text': '继续确认 request_id 的业务作用域。'},
]
# Handwritten for the demo. A real summary could be generated by a model.
summary = '目标：修复重复下单。已知：重复请求测试失败。待确认：request_id 作用域。'
active = rebuild_context(history, summary)

assert len(active) == 3
assert active[-1]['text'] == '不能修改现有接口字段。'
assert not any(e['kind'] == 'tool_result' for e in active)
assert any(e['kind'] == 'tool_result' for e in history)

print(f'原始历史：{len(history)} 项；新上下文：{len(active)} 项')
for event in active:
    print(f"{event['kind']}: {event['text']}")
